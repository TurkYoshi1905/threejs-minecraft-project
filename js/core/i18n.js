const LANG_KEY = 'mc-lang';
const NAME_KEY = 'mc-player-name';

export function getLang() {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === 'en' ? 'en' : 'tr';
  } catch { return 'tr'; }
}
export function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang === 'en' ? 'en' : 'tr'); } catch {}
  try { window.dispatchEvent(new CustomEvent('langchange', { detail: lang })); } catch {}
}
export function getPlayerName() {
  try { return localStorage.getItem(NAME_KEY) || 'Steve'; } catch { return 'Steve'; }
}
export function setPlayerName(name) {
  const clean = (name || '').trim().slice(0, 16) || 'Steve';
  try { localStorage.setItem(NAME_KEY, clean); } catch {}
  try { window.dispatchEvent(new CustomEvent('namechange', { detail: clean })); } catch {}
}
export function t(key, ...args) {
  const lang = getLang();
  const dict = LANGS[lang] || LANGS.tr;
  let s = dict[key];
  if (s == null) s = LANGS.tr[key];
  if (s == null) return key;
  if (!args.length) return s;
  return s.replace(/\{(\d+)\}/g, (_, i) => (args[+i] != null ? String(args[+i]) : ''));
}
export function applyI18n(root = document) {
  const qsa = root.querySelectorAll ? root.querySelectorAll.bind(root) : () => [];
  for (const el of qsa('[data-i18n]')) {
    const key = el.getAttribute('data-i18n');
    const html = el.hasAttribute('data-i18n-html');
    const val = t(key);
    if (html) el.innerHTML = val; else el.textContent = val;
  }
  for (const el of qsa('[data-i18n-placeholder]')) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  }
  for (const el of qsa('[data-i18n-title]')) {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  }
  for (const el of qsa('input[data-i18n-value]')) {
    el.value = t(el.getAttribute('data-i18n-value'));
  }
  document.documentElement.lang = getLang() === 'en' ? 'en' : 'tr';
}
export function langName(code) { return code === 'en' ? 'English' : 'Türkçe'; }
